import { existsSync, readFileSync } from 'node:fs';
import { describe as suite, expect, it } from 'vitest';
import { PATHS, PATH_IDS, describe, excerpt, lastStep, lookLines, stageAt } from './model';

const KERNELS = new URL('../../../../kernels/ch0-2-software-stack/', import.meta.url);
const read = (file: string) => readFileSync(new URL(file, KERNELS), 'utf8');
const ids = (path: (typeof PATH_IDS)[number]) => PATHS[path].stages.map((s) => s.id);

suite('compile pipeline model', () => {
	it('walks each path from source to GPU in order', () => {
		expect(ids('triton')).toEqual(['source', 'ttir', 'ttgir', 'llir', 'ptx', 'sass', 'gpu']);
		expect(ids('numba')).toEqual(['source', 'nvvm', 'ptx', 'sass', 'gpu']);
		expect(ids('cuda')).toEqual(['source', 'ptx', 'sass', 'fatbin', 'gpu']);
	});

	it('maps every step to a stage and clamps out-of-range steps', () => {
		expect(lastStep('triton')).toBe(6);
		expect(lastStep('numba')).toBe(4);
		expect(stageAt('triton', 0).id).toBe('source');
		expect(stageAt('triton', 4).id).toBe('ptx');
		expect(stageAt('triton', -3).id).toBe('source');
		expect(stageAt('numba', 99).id).toBe('gpu');
		expect(describe('numba', 2)).toMatch(/^Numba, stage 3 of 5: PTX\./);
	});

	it('only the CUDA C++ path uses commands instead of generated listings', () => {
		for (const id of PATH_IDS) {
			for (const s of PATHS[id].stages) {
				if (s.commands) expect(id).toBe('cuda');
				if (id === 'cuda' && s.id !== 'source' && s.id !== 'gpu') expect(s.commands).toBeTruthy();
				if (s.id !== 'gpu' && !s.commands) expect(s.file).toBeTruthy();
			}
		}
	});

	it('slices contiguous excerpts by marker or by count', () => {
		const text = 'a\nb start\nc\nd end\ne\n';
		expect(excerpt(text, { start: 'start', end: 'end' })).toEqual({ code: 'b start\nc\nd end', from: 2, to: 4, total: 5 });
		expect(excerpt(text, { start: 'c', count: 10 })).toMatchObject({ code: 'c\nd end\ne', from: 3, to: 5 });
		expect(() => excerpt(text, { start: 'missing' })).toThrow();
		expect(lookLines('x\ny ld\nld z', ['ld'])).toEqual([2, 3]);
	});
});

suite('generated listings', () => {
	it('contain the real tool output the chapter describes', () => {
		for (const name of ['numba.ptx', 'triton.ptx']) {
			const ptx = read(`generated/${name}`);
			expect(ptx).toMatch(/^\.version \d+\.\d+$/m);
			expect(ptx).toContain('.target sm_80');
			expect(ptx).toContain('fma.rn.f32');
		}
		expect(read('generated/numba.ptx')).toContain('Generated by NVIDIA NVVM Compiler');
		expect(read('generated/triton.ptx')).toContain('Generated by LLVM NVPTX Back-End');
		for (const name of ['numba.sass', 'triton.sass']) {
			const sass = read(`generated/${name}`);
			expect(sass).toContain('code for sm_80');
			expect(sass).toMatch(/\bFFMA\b/);
			expect(sass).toMatch(/\bEXIT\b/);
		}
		expect(read('generated/triton.ttir')).toContain('tt.func public @saxpy');
		expect(read('generated/triton.ttgir')).toContain('ttg.target = "cuda:80"');
		expect(read('generated/triton.llir')).toContain('define ptx_kernel void @saxpy');
		expect(read('generated/numba.ll')).toContain('target triple = "nvptx64-nvidia-cuda"');
		expect(read('generated/VERSIONS.txt')).toContain('Target: sm_80');
	});

	it('has every listing a stage points to, with its excerpt and highlighted strings', () => {
		for (const id of PATH_IDS) {
			for (const s of PATHS[id].stages) {
				if (!s.file) continue;
				expect(existsSync(new URL(s.file, KERNELS)), s.file).toBe(true);
				const ex = excerpt(read(s.file), s.excerpt ?? { start: '' });
				expect(ex.code.length, `${id}/${s.id}`).toBeGreaterThan(0);
				for (const token of s.look ?? []) expect(ex.code, `${id}/${s.id}: ${token}`).toContain(token);
			}
		}
	});

	it('backs the numbers quoted in the notices', () => {
		const ttgir = read('generated/triton.ttgir');
		expect(ttgir).toContain('sizePerThread = [4], threadsPerWarp = [32], warpsPerCTA = [4]');
		const fma = (t: string) => (t.match(/fma\.rn\.f32/g) ?? []).length;
		expect(fma(read('generated/triton.ptx'))).toBe(8);
		const llir = read('generated/triton.llir');
		expect((llir.match(/= fmul float/g) ?? []).length).toBe(8);
		expect((llir.match(/= fadd float/g) ?? []).length).toBe(8);
		const sass = read('generated/triton.sass');
		expect((sass.match(/\bFFMA\b/g) ?? []).length).toBe(8);
		expect(sass).toMatch(/\bLDG\.E\b/);
		expect(sass).toMatch(/\bSTG\.E\b/);
		const nbSass = read('generated/numba.sass');
		expect(nbSass).toMatch(/\bLD\.E\b/);
		expect(nbSass).not.toMatch(/\bLDG\b/);
		expect(read('generated/numba.ptx')).toContain('.version 9.4');
		expect(read('generated/triton.ptx')).toContain('.reqntid 128');
	});
});
