"""Compile the CUDA kernels (with NVRTC) and the Triton kernels for sm_80, save
the Triton PTX to generated/, and write generated/summary.txt: how many warp
shuffles, barriers, shared memory accesses and global atomics each kernel has.

Needs no GPU, no driver and no nvcc: NVRTC comes from the cuda-bindings
package, and Triton uses the ptxas it ships.

    python kernels/ch13-reduction/generate.py

The chapter reads generated/summary.txt. Rerun this script after changing a
kernel or a pinned version, and commit the results.
"""

import os
import platform
import re
import sys
import tempfile
import types
from importlib import metadata
from pathlib import Path

# The interpreter cannot emit GPU code.
os.environ.pop("TRITON_INTERPRET", None)
# Triton's cache key ignores the source file path, so compile into a fresh cache.
os.environ["TRITON_CACHE_DIR"] = tempfile.mkdtemp(prefix="triton-cache-")

import triton
from cuda.bindings import nvrtc
from triton.backends.compiler import GPUTarget

HERE = Path(__file__).resolve().parent
OUT = HERE / "generated"
CC = 80
CUDA_KERNELS = ["reduce_interleaved", "reduce_sequential", "reduce_warp_final", "reduce_atomic"]
COLUMNS = {
    "shfl.sync": r"\bshfl\.sync\.",
    "bar.sync": r"\bbar\.sync\b",
    "st.shared": r"\bst\.shared",
    "ld.shared": r"\bld\.shared",
    "atom/red.global": r"\b(atom|red)\.global",
}


def load(relpath, name):
    # A relative path keeps this machine's directory names out of the listings.
    module = types.ModuleType(name)
    module.__file__ = relpath
    sys.modules[name] = module
    exec(compile(Path(relpath).read_text(), relpath, "exec"), module.__dict__)
    return module


def write(name, text):
    (OUT / name).write_text(text.rstrip("\n") + "\n")
    print(f"wrote generated/{name}")


def check(result):
    err, *rest = result
    if err != nvrtc.nvrtcResult.NVRTC_SUCCESS:
        raise RuntimeError(err)
    return rest[0] if rest else None


def cuda_ptx():
    src = (HERE / "cuda/reduce_kernels.cuh").read_bytes()
    prog = check(nvrtc.nvrtcCreateProgram(src, b"reduce_kernels.cu", 0, [], []))
    opts = [f"--gpu-architecture=compute_{CC}".encode(), b"-std=c++17"]
    check(nvrtc.nvrtcCompileProgram(prog, len(opts), opts))
    ptx = b" " * check(nvrtc.nvrtcGetPTXSize(prog))
    check(nvrtc.nvrtcGetPTX(prog, ptx))
    return ptx.decode().rstrip("\x00")


def entries(ptx):
    # Split the module at each .entry so every kernel is counted on its own.
    parts = re.split(r"(?=\.visible \.entry )", ptx)
    return {re.search(r"\.entry (\w+)", p).group(1): p for p in parts if ".entry" in p}


def row(name, text, num_warps="-"):
    counts = [len(re.findall(pattern, text)) for pattern in COLUMNS.values()]
    return f"{name:<20}" + "".join(f"{n:>{len(c) + 2}}" for n, c in zip(counts, COLUMNS)) + f"{num_warps:>11}"


if __name__ == "__main__":
    os.chdir(HERE)
    OUT.mkdir(exist_ok=True)
    header = f"{'kernel':<20}" + "".join(f"{c:>{len(c) + 2}}" for c in COLUMNS) + f"{'num_warps':>11}"
    lines = [
        "Generated by generate.py. Do not edit by hand.",
        f"target sm_{CC}; cuda-bindings {metadata.version('cuda-bindings')} (NVRTC), "
        f"triton {metadata.version('triton')}, Python {platform.python_version()}",
        "Counts are PTX instructions in the kernel body, not executions.",
        "",
        "CUDA C++, cuda/reduce_kernels.cuh",
        header,
    ]
    by_entry = entries(cuda_ptx())
    for name in CUDA_KERNELS:
        mangled = next(k for k in by_entry if name in k)
        lines.append(row(name, by_entry[mangled]))

    tr = load("triton/reduce.py", "reduce_triton")
    signature = {"x_ptr": "*fp32", "out_ptr": "*fp32", "n": "i32", "BLOCK": "constexpr"}
    # The hint triton.jit adds at launch for 16-byte aligned pointers and sizes.
    aligned = [["tt.divisibility", 16]]
    attrs = {(0,): aligned, (1,): aligned, (2,): aligned}
    lines += ["", f"Triton, triton/reduce.py, BLOCK={tr.BLOCK}, n assumed a multiple of 16", header]
    for fn in (tr.partial_sums_kernel, tr.atomic_sum_kernel):
        src = triton.compiler.ASTSource(fn=fn, signature=signature, constexprs={"BLOCK": tr.BLOCK}, attrs=attrs)
        k = triton.compile(src, target=GPUTarget("cuda", CC, 32))
        write(f"{fn.__name__}.ptx", k.asm["ptx"])
        lines.append(row(fn.__name__, k.asm["ptx"], k.metadata.num_warps))
    write("summary.txt", "\n".join(lines))
