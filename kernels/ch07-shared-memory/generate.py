"""Compile the tiled Numba kernel and the Triton kernel for sm_80 and save
where each one uses shared memory to generated/.

Needs no GPU, no driver and no nvcc: Numba uses NVVM from the numba-cuda
wheels, and Triton uses the ptxas it ships.

    python kernels/ch07-shared-memory/generate.py

The chapter shows generated/shared_ops.txt as it is. Rerun this script after
changing a kernel or a pinned version, and commit the results.
"""

import os
import platform
import re
import sys
import tempfile
import types
from importlib import metadata
from pathlib import Path

# These switch Numba and Triton to CPU modes that cannot emit GPU code.
os.environ.pop("NUMBA_ENABLE_CUDASIM", None)
os.environ.pop("TRITON_INTERPRET", None)
# A fresh cache, so no build from an earlier run is reused.
os.environ["TRITON_CACHE_DIR"] = tempfile.mkdtemp(prefix="triton-cache-")

import numpy as np
import triton
from numba import cuda, float32
from triton.backends.compiler import GPUTarget

HERE = Path(__file__).resolve().parent
OUT = HERE / "generated"
CC = (8, 0)


def load(relpath, name):
    # A relative path keeps this machine's directory names out of the listings.
    module = types.ModuleType(name)
    module.__file__ = relpath
    sys.modules[name] = module
    exec(compile(Path(relpath).read_text(), relpath, "exec"), module.__dict__)
    return module


def write(name, text):
    (OUT / name).write_text(text.rstrip("\n") + "\n")
    print(f"wrote generated/{name}")


def matching(text, pattern):
    # Drop the location suffixes MLIR adds, so the lines fit on a page.
    lines = [re.sub(r"\s+loc\(#loc\d*\)$", "", line.strip()) for line in text.splitlines() if re.search(pattern, line)]
    return "\n".join(lines)


def shorten_loads(text):
    # The unrolled inner loop has one ld.shared per As and Bs read; keep the first two of each run.
    out, run = [], 0
    for line in text.splitlines() + [""]:
        if line.startswith("ld.shared"):
            run += 1
            if run <= 2:
                out.append(line)
            continue
        if run > 2:
            out.append(f"... {run - 2} more ld.shared.f32, {run} in this run")
        run = 0
        out.append(line)
    return "\n".join(out).rstrip("\n")


def numba_ptx():
    nb = load("numba/matmul.py", "matmul")
    sig = (float32[:, :], float32[:, :], float32[:, :])
    ptx, _ = cuda.compile_ptx(nb.matmul_tiled.py_func, sig, cc=CC)
    write("numba_tiled.ptx", ptx)
    return ptx


def triton_ir():
    tr = load("triton/matmul.py", "matmul_triton")
    signature = {"a_ptr": "*fp32", "b_ptr": "*fp32", "c_ptr": "*fp32", "n": "i32", "BLOCK": "constexpr"}
    # The hint triton.jit adds at launch when an address is a multiple of 16 bytes, as PyTorch allocations are.
    aligned = [["tt.divisibility", 16]]
    attrs = {(0,): aligned, (1,): aligned, (2,): aligned}
    src = triton.compiler.ASTSource(fn=tr.matmul_kernel, signature=signature, constexprs={"BLOCK": tr.BLOCK}, attrs=attrs)
    kernel = triton.compile(src, target=GPUTarget("cuda", CC[0] * 10 + CC[1], 32))
    # tl.cdiv is inlined from Triton's own source; hide where this machine installed it.
    write("triton.ttgir", re.sub(r'"[^"]*site-packages/', '"<site-packages>/', kernel.asm["ttgir"]))
    return kernel, tr.BLOCK


def main():
    os.chdir(HERE)
    OUT.mkdir(exist_ok=True)
    ptx = numba_ptx()
    kernel, block = triton_ir()
    m = kernel.metadata
    ptx_tr = kernel.asm["ptx"]
    report = [
        "Generated by generate.py from numba/matmul.py and triton/matmul.py. Do not edit by hand.",
        f"Target: sm_{CC[0]}{CC[1]}",
        "",
        "Numba matmul_tiled, PTX: shared arrays, shared loads and stores, barriers",
        shorten_loads(matching(ptx, r"\.shared|bar\.sync")),
        "",
        f"Triton matmul_kernel, TTGIR (BLOCK={block}, num_warps={m.num_warps}, num_stages={m.num_stages}):"
        " shared memory buffers and copies",
        matching(kernel.asm["ttgir"], r"ttg\.(local_alloc|local_load|local_store|async_copy|async_wait|memdesc)"),
        "",
        f"Triton shared memory per program: {m.shared} bytes",
        "Triton PTX, lines that start with each instruction: "
        + ", ".join(f"{len(re.findall(rf'^\s*{op}', ptx_tr, re.M))} {op}" for op in ("bar.sync", "cp.async", "ld.shared", "st.shared", "ldmatrix")),
    ]
    write("shared_ops.txt", "\n".join(report))
    v = metadata.version
    write(
        "VERSIONS.txt",
        "\n".join(
            [
                "Generated by generate.py. Do not edit by hand.",
                f"Python {platform.python_version()}, NumPy {np.__version__}",
                f"numba {v('numba')}, numba-cuda {v('numba-cuda')}",
                f"triton {v('triton')}",
            ]
        ),
    )


if __name__ == "__main__":
    main()
