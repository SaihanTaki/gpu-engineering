"""Compile the chapter's Numba and Triton SAXPY kernels for sm_80 and save
every stage of each pipeline to generated/.

Needs no GPU, no driver and no nvcc: Numba uses NVVM and nvJitLink from the
numba-cuda[cu13] wheels, and Triton uses the ptxas and cuobjdump it ships.

    python kernels/ch0-2-software-stack/generate.py

The site shows these files as they are. Rerun this script after changing a
kernel or a pinned version, and commit the results.
"""

import os
import platform
import re
import subprocess
import sys
import tempfile
import types
from importlib import metadata
from pathlib import Path

# These switch Numba and Triton to CPU modes that cannot emit GPU code.
os.environ.pop("NUMBA_ENABLE_CUDASIM", None)
os.environ.pop("TRITON_INTERPRET", None)
# Triton's cache key ignores the source file path, so a cached build could
# carry paths from an earlier run. Compile into a fresh cache every time.
os.environ["TRITON_CACHE_DIR"] = tempfile.mkdtemp(prefix="triton-cache-")

import numpy as np

# numba-cuda 0.30.4 registers an overload for np.row_stack, which NumPy 2.5
# removed. Its CUDA target fails to import without this alias.
if not hasattr(np, "row_stack"):
    np.row_stack = np.vstack

import triton
from numba import cuda, float32
from numba.cuda.compiler import _compile_pyfunc_with_fixup
from triton.backends.compiler import GPUTarget
from triton.backends.nvidia.compiler import get_ptxas

HERE = Path(__file__).resolve().parent
OUT = HERE / "generated"
CC = (8, 0)
TRITON_BLOCK = 1024
CUOBJDUMP = Path(triton.backends.nvidia.__file__).parent / "bin" / "cuobjdump"


def load(relpath, name):
    # A relative path keeps the source locations in the listings free of
    # this machine's directory names.
    module = types.ModuleType(name)
    module.__file__ = relpath
    sys.modules[name] = module
    exec(compile(Path(relpath).read_text(), relpath, "exec"), module.__dict__)
    return module


def write(name, data):
    path = OUT / name
    if isinstance(data, bytes):
        path.write_bytes(data)
    else:
        path.write_text(data.rstrip("\n") + "\n")
    print(f"wrote {path.relative_to(HERE)}")


def sass(cubin_name):
    out = subprocess.run(
        [str(CUOBJDUMP), "-sass", str(OUT / cubin_name)], check=True, capture_output=True, text=True
    )
    return out.stdout


def tool_version(path):
    out = subprocess.run([str(path), "--version"], check=True, capture_output=True, text=True)
    return out.stdout.strip().splitlines()[-2]


def numba_stages():
    nb = load("numba/saxpy.py", "saxpy")
    sig = (float32, float32[:], float32[:], float32[:])
    # compile_ptx returns only the PTX. This internal helper is what it calls,
    # and the library it returns also holds the NVVM IR and can link a cubin.
    lib, _ = _compile_pyfunc_with_fixup(nb.saxpy.py_func, sig, device=False, cc=CC, abi="numba")
    write("numba.ll", lib.get_llvm_str())
    ptx = lib.get_asm_str(cc=CC)
    public, _ = cuda.compile_ptx(nb.saxpy.py_func, sig, cc=CC)
    # Names carry a per-compile counter (B2v1B, B2v2B, ...); nothing else may differ.
    same = re.sub(r"B2v\d+B", "", ptx) == re.sub(r"B2v\d+B", "", public)
    assert same, "internal PTX differs from cuda.compile_ptx"
    write("numba.ptx", ptx)
    write("numba.cubin", bytes(lib.get_cubin(cc=CC).code))
    write("numba.sass", sass("numba.cubin"))


def triton_stages():
    tr = load("triton/saxpy.py", "saxpy_triton")
    signature = {"a": "fp32", "x_ptr": "*fp32", "y_ptr": "*fp32", "out_ptr": "*fp32", "n": "i32", "BLOCK": "constexpr"}
    # The same hint triton.jit adds at launch when a tensor's address is a
    # multiple of 16 bytes, which PyTorch allocations are.
    aligned = [["tt.divisibility", 16]]
    attrs = {(1,): aligned, (2,): aligned, (3,): aligned}
    src = triton.compiler.ASTSource(fn=tr.saxpy, signature=signature, constexprs={"BLOCK": TRITON_BLOCK}, attrs=attrs)
    kernel = triton.compile(src, target=GPUTarget("cuda", CC[0] * 10 + CC[1], 32))
    for stage in ("ttir", "ttgir", "llir", "ptx"):
        write(f"triton.{stage}", kernel.asm[stage])
    write("triton.cubin", kernel.asm["cubin"])
    write("triton.sass", sass("triton.cubin"))
    return kernel.metadata


def nvvm_version():
    from numba.cuda.cudadrv import nvvm

    return ".".join(map(str, nvvm.NVVM().get_version()))


def versions(meta):
    from cuda.core import Linker

    v = metadata.version
    lines = [
        "Generated by generate.py. Do not edit by hand.",
        f"Target: sm_{CC[0]}{CC[1]} (compute capability {CC[0]}.{CC[1]})",
        f"Python {platform.python_version()}, NumPy {np.__version__}",
        "",
        "Numba path",
        f"  numba {v('numba')}, numba-cuda {v('numba-cuda')}, llvmlite {v('llvmlite')}",
        f"  NVVM {nvvm_version()} (nvidia-nvvm {v('nvidia-nvvm')})",
        f"  cubin linked with {Linker.which_backend()} (nvidia-nvjitlink {v('nvidia-nvjitlink')})",
        "",
        "Triton path",
        f"  triton {v('triton')}, num_warps={meta.num_warps}, BLOCK={TRITON_BLOCK}",
        f"  ptxas: {tool_version(get_ptxas(CC[0] * 10 + CC[1]).path)}",
        "",
        "Disassembly",
        f"  cuobjdump (bundled with triton): {tool_version(CUOBJDUMP)}",
    ]
    write("VERSIONS.txt", "\n".join(lines))


if __name__ == "__main__":
    os.chdir(HERE)
    OUT.mkdir(exist_ok=True)
    numba_stages()
    versions(triton_stages())
    sys.exit(0)
