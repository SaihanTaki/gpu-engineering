"""Compile both Triton transposes for sm_80 and save their TTGIR and PTX to
generated/, plus a summary of the shared memory instructions in each.

Needs no GPU, no driver and no nvcc: Triton uses the ptxas it ships.

    python kernels/ch11-transpose/generate.py

The chapter reads generated/summary.txt. Rerun this script after changing a
kernel or the pinned Triton version, and commit the results.
"""

import os
import platform
import re
import sys
import tempfile
import types
from importlib import metadata
from pathlib import Path

# The interpreter cannot emit GPU code.
os.environ.pop("TRITON_INTERPRET", None)
# Triton's cache key ignores the source file path, so compile into a fresh cache.
os.environ["TRITON_CACHE_DIR"] = tempfile.mkdtemp(prefix="triton-cache-")

import triton
from triton.backends.compiler import GPUTarget

HERE = Path(__file__).resolve().parent
OUT = HERE / "generated"
CC = 80


def load(relpath, name):
    # A relative path keeps this machine's directory names out of the listings.
    module = types.ModuleType(name)
    module.__file__ = relpath
    sys.modules[name] = module
    exec(compile(Path(relpath).read_text(), relpath, "exec"), module.__dict__)
    return module


def write(name, text):
    (OUT / name).write_text(text.rstrip("\n") + "\n")
    print(f"wrote generated/{name}")


def count(pattern, text):
    return len(re.findall(pattern, text))


if __name__ == "__main__":
    os.chdir(HERE)
    OUT.mkdir(exist_ok=True)
    tr = load("triton/transpose.py", "transpose_triton")
    signature = {"in_ptr": "*fp32", "out_ptr": "*fp32", "rows": "i32", "cols": "i32", "BLOCK": "constexpr"}
    # The hint triton.jit adds at launch for 16-byte aligned pointers and sizes.
    aligned = [["tt.divisibility", 16]]
    attrs = {(0,): aligned, (1,): aligned, (2,): aligned, (3,): aligned}
    lines = [
        "Generated by generate.py. Do not edit by hand.",
        f"triton {metadata.version('triton')}, target sm_{CC}, BLOCK={tr.BLOCK}, Python {platform.python_version()}",
        "rows and cols assumed multiples of 16 (the launch-time divisibility hint).",
        "",
        "variant  convert_layout  local_alloc  st.shared  ld.shared  bar.sync  num_warps",
    ]
    for variant, fn in tr.KERNELS.items():
        src = triton.compiler.ASTSource(fn=fn, signature=signature, constexprs={"BLOCK": tr.BLOCK}, attrs=attrs)
        k = triton.compile(src, target=GPUTarget("cuda", CC, 32))
        ttgir, ptx = k.asm["ttgir"], k.asm["ptx"]
        write(f"triton_{variant}.ttgir", ttgir)
        write(f"triton_{variant}.ptx", ptx)
        row = [
            count(r"ttg\.convert_layout", ttgir),
            count(r"ttg\.local_alloc", ttgir),
            count(r"\bst\.shared", ptx),
            count(r"\bld\.shared", ptx),
            count(r"\bbar\.sync", ptx),
            k.metadata.num_warps,
        ]
        lines.append(f"{variant:<8} " + " ".join(f"{n:>{w}}" for n, w in zip(row, (14, 12, 10, 10, 9, 10))))
    write("summary.txt", "\n".join(lines))
