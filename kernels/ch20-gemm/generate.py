"""Compile the CUDA kernels (with NVRTC) and one Triton config for sm_80 and
write generated/summary.txt: how many global loads, shared loads and
multiply-adds each kernel's PTX has, and how wide the loads are.

Needs no GPU, no driver and no nvcc: NVRTC comes from the cuda-bindings
package, and Triton uses the ptxas it ships.

    python kernels/ch20-gemm/generate.py

The chapter reads generated/summary.txt. Rerun this script after changing a
kernel or a pinned version, and commit the results.
"""

import os
import platform
import re
import sys
import tempfile
import types
from importlib import metadata
from pathlib import Path

# The interpreter cannot emit GPU code.
os.environ.pop("TRITON_INTERPRET", None)
# Triton's cache key ignores the source file path, so compile into a fresh cache.
os.environ["TRITON_CACHE_DIR"] = tempfile.mkdtemp(prefix="triton-cache-")

import triton
from cuda.bindings import nvrtc
from triton.backends.compiler import GPUTarget

HERE = Path(__file__).resolve().parent
OUT = HERE / "generated"
CC = 80
SIG = "(const float *, const float *, float *, int, int, int)"
CUDA_KERNELS = [
    ("gemm_naive", "gemm_naive", None),
    ("gemm_coalesced", "gemm_coalesced", None),
    ("gemm_smem<32,32,32>", "gemm_smem", "<32, 32, 32>"),
    ("gemm_1d<64,64,8,8>", "gemm_1d", "<64, 64, 8, 8>"),
    ("gemm_2d<128,128,8,8,8>", "gemm_2d", "<128, 128, 8, 8, 8>"),
    ("gemm_vec<128,128,8,8,8>", "gemm_vec", "<128, 128, 8, 8, 8>"),
]
COLUMNS = {
    "ld.global": r"\bld\.global(?:\.nc)?\.(?:f32|b32)\b",
    "ld.global.v4": r"\bld\.global(?:\.nc)?\.v4\.(?:f32|b32)\b",
    "cp.async": r"\bcp\.async\.c[ag]\.shared\.global",
    "ld.shared": r"\bld\.shared\.(?:f32|b32)\b",
    "ld.shared.v4": r"\bld\.shared\.v4\.(?:f32|b32)\b",
    "fma.f32": r"\bfma\.rn\.f32",
    "mma": r"\bmma\.sync",
}


def load(relpath, name):
    # A relative path keeps this machine's directory names out of the listings.
    module = types.ModuleType(name)
    module.__file__ = relpath
    sys.modules[name] = module
    exec(compile(Path(relpath).read_text(), relpath, "exec"), module.__dict__)
    return module


def write(name, text):
    (OUT / name).write_text(text.rstrip("\n") + "\n")
    print(f"wrote generated/{name}")


def check(result):
    err, *rest = result
    if err != nvrtc.nvrtcResult.NVRTC_SUCCESS:
        raise RuntimeError(err)
    return rest[0] if rest else None


def cuda_ptx():
    src = (HERE / "cuda/gemm_kernels.cuh").read_text()
    src += "".join(f"\ntemplate __global__ void {fn}{args}{SIG};" for _, fn, args in CUDA_KERNELS if args)
    prog = check(nvrtc.nvrtcCreateProgram(src.encode(), b"gemm_kernels.cu", 0, [], []))
    opts = [f"--gpu-architecture=compute_{CC}".encode(), b"-std=c++17"]
    check(nvrtc.nvrtcCompileProgram(prog, len(opts), opts))
    ptx = b" " * check(nvrtc.nvrtcGetPTXSize(prog))
    check(nvrtc.nvrtcGetPTX(prog, ptx))
    return ptx.decode().rstrip("\x00")


def entries(ptx):
    # Split the module at each .entry so every kernel is counted on its own.
    parts = re.split(r"(?=\.(?:visible|weak) \.entry )", ptx)
    return {re.search(r"\.entry (\w+)", p).group(1): p for p in parts if ".entry" in p}


def row(name, text):
    counts = [len(re.findall(pattern, text)) for pattern in COLUMNS.values()]
    return f"{name:<26}" + "".join(f"{n:>{len(c) + 2}}" for n, c in zip(counts, COLUMNS))


if __name__ == "__main__":
    os.chdir(HERE)
    OUT.mkdir(exist_ok=True)
    header = f"{'kernel':<26}" + "".join(f"{c:>{len(c) + 2}}" for c in COLUMNS)
    lines = [
        "Generated by generate.py. Do not edit by hand.",
        f"target sm_{CC}; cuda-bindings {metadata.version('cuda-bindings')} (NVRTC), "
        f"triton {metadata.version('triton')}, Python {platform.python_version()}",
        "Counts are PTX instructions in the kernel body, not executions; loops may be partly unrolled.",
        "",
        "CUDA C++, cuda/gemm_kernels.cuh",
        header,
    ]
    by_entry = entries(cuda_ptx())
    for label, fn, args in CUDA_KERNELS:
        mangled = next(k for k in by_entry if re.search(rf"\d{fn}(I|P)", k))
        lines.append(row(label, by_entry[mangled]))

    tr = load("triton/gemm.py", "gemm_triton")
    signature = {"a_ptr": "*fp32", "b_ptr": "*fp32", "c_ptr": "*fp32", "M": "i32", "N": "i32", "K": "i32"}
    constexprs = {"BM": 128, "BN": 128, "BK": 32}
    signature.update({k: "constexpr" for k in constexprs})
    # The hint triton.jit adds at launch for 16-byte aligned pointers and sizes.
    aligned = [["tt.divisibility", 16]]
    attrs = {(i,): aligned for i in range(6)}
    # gemm_kernel is the autotuner; .fn is the jitted kernel under it.
    src = triton.compiler.ASTSource(fn=tr.gemm_kernel.fn, signature=signature, constexprs=constexprs, attrs=attrs)
    k = triton.compile(src, target=GPUTarget("cuda", CC, 32), options={"num_warps": 8, "num_stages": 3})
    lines += [
        "",
        "Triton, triton/gemm.py, one autotune config: BM=128 BN=128 BK=32, num_warps=8, num_stages=3,",
        "sizes assumed multiples of 16",
        header,
        row("gemm_kernel", k.asm["ptx"]),
    ]
    write("summary.txt", "\n".join(lines))
