"""Compile both Triton histograms for sm_80 and save their PTX to generated/,
plus a count of the atomic instructions in each.

Needs no GPU, no driver and no nvcc: Triton uses the ptxas it ships.

    python kernels/ch15-histogram/generate.py

The chapter reads generated/summary.txt. Rerun this script after changing a
kernel or the pinned Triton version, and commit the results.
"""

import os
import platform
import re
import sys
import tempfile
import types
from importlib import metadata
from pathlib import Path

# The interpreter cannot emit GPU code.
os.environ.pop("TRITON_INTERPRET", None)
# Triton's cache key ignores the source file path, so compile into a fresh cache.
os.environ["TRITON_CACHE_DIR"] = tempfile.mkdtemp(prefix="triton-cache-")

import triton
from triton.backends.compiler import GPUTarget

HERE = Path(__file__).resolve().parent
OUT = HERE / "generated"
CC = 80


def load(relpath, name):
    # A relative path keeps this machine's directory names out of the listings.
    module = types.ModuleType(name)
    module.__file__ = relpath
    sys.modules[name] = module
    exec(compile(Path(relpath).read_text(), relpath, "exec"), module.__dict__)
    return module


def write(name, text):
    (OUT / name).write_text(text.rstrip("\n") + "\n")
    print(f"wrote generated/{name}")


def count(pattern, text):
    return len(re.findall(pattern, text))


if __name__ == "__main__":
    os.chdir(HERE)
    OUT.mkdir(exist_ok=True)
    tr = load("triton/histogram.py", "histogram_triton")
    signature = {"data_ptr": "*u8", "hist_ptr": "*i32", "n": "i32", "BLOCK": "constexpr"}
    constexprs = {"BLOCK": tr.BLOCK}
    kernels = {"atomic": tr.hist_atomic_kernel, "local": tr.hist_local_kernel}
    lines = [
        "Generated by generate.py. Do not edit by hand.",
        f"triton {metadata.version('triton')}, target sm_{CC}, BLOCK={tr.BLOCK}, BINS={tr.BINS}, Python {platform.python_version()}",
        "Counts are static instructions in the PTX, not executions.",
        "",
        "variant  atom.global  red.global  atom.shared  red.shared  bar.sync  num_warps",
    ]
    for variant, fn in kernels.items():
        sig = dict(signature)
        cx = dict(constexprs)
        if variant == "local":
            sig["BINS"] = "constexpr"
            cx["BINS"] = tr.BINS
        src = triton.compiler.ASTSource(fn=fn, signature=sig, constexprs=cx)
        k = triton.compile(src, target=GPUTarget("cuda", CC, 32))
        ptx = k.asm["ptx"]
        write(f"triton_{variant}.ptx", ptx)
        row = [
            # Qualifiers such as .relaxed or .gpu can sit on either side of the state space.
            count(r"\batom(\.\w+)*\.global\b", ptx),
            count(r"\bred(\.\w+)*\.global\b", ptx),
            count(r"\batom(\.\w+)*\.shared\b", ptx),
            count(r"\bred(\.\w+)*\.shared\b", ptx),
            count(r"\bbar\.sync", ptx),
            k.metadata.num_warps,
        ]
        lines.append(f"{variant:<8} " + " ".join(f"{n:>{w}}" for n, w in zip(row, (11, 11, 12, 11, 9, 10))))
    write("summary.txt", "\n".join(lines))
