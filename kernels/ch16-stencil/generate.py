"""Compile the chapter's kernels for sm_80 with a 5 x 5 filter (R = 2) and
count the memory instructions in their PTX. Needs no GPU, no driver and no nvcc.

- generated/summary.txt: per kernel, how many PTX instructions load from
  constant, global and shared memory, store to shared memory, and wait at a
  barrier. Counts are of instructions in the code, after unrolling, not of
  how often they run.

    python kernels/ch16-stencil/generate.py

Rerun after changing a kernel or a pinned version, and commit the result.
"""

import os
import platform
import re
import sys
import tempfile
import types
from importlib import metadata
from pathlib import Path

# These switch Numba and Triton to CPU modes that cannot emit GPU code.
os.environ.pop("NUMBA_ENABLE_CUDASIM", None)
os.environ.pop("TRITON_INTERPRET", None)
# Triton's cache key ignores the source file path, so compile into a fresh cache.
os.environ["TRITON_CACHE_DIR"] = tempfile.mkdtemp(prefix="triton-cache-")

import numpy as np
import triton
from cuda.bindings import nvrtc
from numba import cuda, float32
from triton.backends.compiler import GPUTarget

HERE = Path(__file__).resolve().parent
OUT = HERE / "generated"
CC = (8, 0)
R = 2
COLUMNS = {
    "ld.const": r"\bld\.const",
    "ld.global": r"\bld\.global",
    "ld.shared": r"\bld\.shared",
    "st.shared": r"\bst\.shared",
    "bar.sync": r"\bbar\.sync",
}


def load(relpath, name):
    # A relative path keeps this machine's directory names out of the output.
    module = types.ModuleType(name)
    module.__file__ = relpath
    sys.modules[name] = module
    exec(compile(Path(relpath).read_text(), relpath, "exec"), module.__dict__)
    return module


def check(result):
    if result[0] != nvrtc.nvrtcResult.NVRTC_SUCCESS:
        raise RuntimeError(f"NVRTC error {result[0]}")
    return result[1:]


def entries(ptx):
    """{kernel name: body} for every .entry in a PTX module."""
    return dict(re.findall(r"\.entry\s+(\w+)\((.*?)\n}", ptx, flags=re.S))


def row(label, body):
    return f"  {label:<14}" + "".join(f"{len(re.findall(p, body)):>11}" for p in COLUMNS.values())


def cuda_cpp():
    src = (HERE / "cuda" / "conv2d_kernels.cuh").read_text()
    src += f"\ntemplate __global__ void conv2d_naive<{R}>(const float *, float *, int, int);"
    src += f"\ntemplate __global__ void conv2d_tiled<{R}>(const float *, float *, int, int);\n"
    (prog,) = check(nvrtc.nvrtcCreateProgram(src.encode(), b"conv2d_kernels.cu", 0, [], []))
    opts = [f"-arch=compute_{CC[0]}{CC[1]}".encode(), b"-std=c++17"]
    err = nvrtc.nvrtcCompileProgram(prog, len(opts), opts)[0]
    if err != nvrtc.nvrtcResult.NVRTC_SUCCESS:
        raise RuntimeError(f"NVRTC compile failed: {err}")
    (size,) = check(nvrtc.nvrtcGetPTXSize(prog))
    ptx = b" " * size
    check(nvrtc.nvrtcGetPTX(prog, ptx))
    kernels = entries(ptx.decode())
    lines = ["CUDA C++ (NVRTC), cuda/conv2d_kernels.cuh"]
    for name in ("naive", "tiled"):
        body = next(b for k, b in kernels.items() if f"conv2d_{name}" in k)
        lines.append(row(f"conv2d_{name}", body))
    return lines


def numba_kernels():
    nb = load("numba/conv2d.py", "conv2d_numba")
    filt = np.arange(1, (2 * R + 1) ** 2 + 1, dtype=np.float32).reshape(2 * R + 1, 2 * R + 1)
    lines = ["Numba (NVVM), numba/conv2d.py"]
    for name, kernel in nb.make_kernels(filt).items():
        ptx, _ = cuda.compile_ptx(kernel.py_func, (float32[:, ::1], float32[:, ::1]), cc=CC)
        lines.append(row(f"conv2d_{name}", ptx))
    return lines


def triton_kernel():
    tr = load("triton/conv2d.py", "conv2d_triton")
    signature = {"in_ptr": "*fp32", "f_ptr": "*fp32", "out_ptr": "*fp32", "h": "i32", "w": "i32",
                 "R": "constexpr", "BLOCK_H": "constexpr", "BLOCK_W": "constexpr"}
    aligned = [["tt.divisibility", 16]]
    attrs = {(0,): aligned, (1,): aligned, (2,): aligned}
    constexprs = {"R": R, "BLOCK_H": tr.BLOCK_H, "BLOCK_W": tr.BLOCK_W}
    src = triton.compiler.ASTSource(fn=tr.conv2d_kernel, signature=signature, constexprs=constexprs, attrs=attrs)
    k = triton.compile(src, target=GPUTarget("cuda", CC[0] * 10 + CC[1], 32))
    loads = [line for line in k.asm["ttgir"].splitlines() if "= tt.load" in line]
    blocks = sum(": tensor<" in line for line in loads)
    return [
        f"Triton, triton/conv2d.py, BLOCK = {tr.BLOCK_H} x {tr.BLOCK_W}, num_warps = {k.metadata.num_warps}",
        row("conv2d_kernel", k.asm["ptx"]),
        f"  TTGIR: {blocks} tt.load of a pixel block, {len(loads) - blocks} of one filter weight, "
        f"{k.asm['ttgir'].count('ttg.local_alloc')} ttg.local_alloc",
    ]


if __name__ == "__main__":
    os.chdir(HERE)
    OUT.mkdir(exist_ok=True)
    v = metadata.version
    major, minor = nvrtc.nvrtcVersion()[1:]
    lines = [
        "Generated by generate.py. Do not edit by hand.",
        f"Target sm_{CC[0]}{CC[1]}, R = {R} (5 x 5 filter), TILE = 16. Python {platform.python_version()},",
        f"NVRTC {major}.{minor}, numba-cuda {v('numba-cuda')}, triton {v('triton')}.",
        "PTX instructions in the code of each kernel:",
        "",
        f"  {'kernel':<14}" + "".join(f"{c:>11}" for c in COLUMNS),
        *cuda_cpp(),
        "",
        *numba_kernels(),
        "",
        *triton_kernel(),
    ]
    (OUT / "summary.txt").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
